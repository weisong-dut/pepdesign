"""氨基酸基础常量表。

设计说明
--------
所有后续的物化性质计算（疏水矩、净电荷、GRAVY、二级结构倾向、聚集倾向……）
都依赖这一张表。把这些"领域常数"独立成一个模块而不是散落在各处，好处是：

1. 单一事实来源：换一种疏水性标度（Kyte-Doolittle vs Eisenberg）时，
   只需要在这里加一张表，全项目同步生效，不会出现两处代码用了两套标度
   却互相比较的隐性 bug。
2. 可被奖励函数直接复用：reward 模块里"结构合理性"这一维会直接用这里的
   Helix/Sheet 倾向值，避免奖励实现和序列工具实现出现口径不一致——
   这是强化学习里非常致命的问题（奖励算的和评估算的不是一回事，
   会导致模型对着错误的梯度方向优化）。
"""

